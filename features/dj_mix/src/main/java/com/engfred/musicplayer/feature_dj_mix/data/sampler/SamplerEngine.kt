package com.engfred.musicplayer.feature_dj_mix.data.sampler

import android.content.Context
import android.media.AudioAttributes
import android.media.SoundPool
import android.util.Log
import androidx.media3.common.util.UnstableApi
import com.engfred.musicplayer.feature_dj_mix.data.crossfade.CrossfadeEngine
import com.engfred.musicplayer.feature_dj_mix.data.crossfade.CrossfadeEngineState
import com.engfred.musicplayer.feature_dj_mix.data.crossfade.MixStrategy
import dagger.hilt.android.qualifiers.ApplicationContext
import kotlinx.coroutines.CoroutineScope
import kotlinx.coroutines.Dispatchers
import kotlinx.coroutines.Job
import kotlinx.coroutines.SupervisorJob
import kotlinx.coroutines.cancel
import kotlinx.coroutines.delay
import kotlinx.coroutines.launch
import javax.inject.Inject
import javax.inject.Singleton

/**
 * Low-latency DJ sampler engine built on Android's [SoundPool].
 *
 * ── Auto-trigger map (TEST BUILD — randomised pools, all samples rotate) ─────
 *
 * Trigger point │ Pool                                          │ Fraction
 * ──────────────┼───────────────────────────────────────────────┼──────────
 * START         │ SIREN, REWIND_SWEEP, FOGHORN                  │ 0 %
 * MID 1         │ RISER_SWEEP, WHITE_NOISE_UP, WHITE_NOISE_DOWN │ 30 %
 * MID 2         │ IMPACT_HIT, STUTTER_HIT                       │ 55 %
 * DROP          │ AIR_HORN, CROWD_HEY                           │ 100 %
 * ─────────────────────────────────────────────────────────────────────────────
 * Session start │ AIR_HORN (once, fired by AutoMixService on first play)
 *
 * All four samples for a given crossfade are chosen ONCE at crossfade-start
 * and stored in [selectedMid1Sample], [selectedMid2Sample], [selectedDropSample]
 * so mid-trigger checks always see a stable, consistent set for that transition.
 *
 * ── Architecture notes ───────────────────────────────────────────────────────
 * - [SoundPool] pre-decodes all audio to raw PCM at load time, so each
 * [triggerSample] fires in < 10 ms — fast enough to feel "live".
 * - Up to [MAX_STREAMS] sounds can overlap simultaneously.
 * - Synthesized samples are generated by [SynthesizedSampleGenerator] on a
 * background coroutine and loaded into SoundPool once their WAV file is ready.
 * - [SamplerEngine] is a @Singleton; call [initialize] from [AutoMixService.onCreate]
 * and [release] from [AutoMixService.releaseAndStop] / [AutoMixService.onDestroy].
 * - Call [onSessionStarted] from [AutoMixService] when the first track begins playing.
 */
@UnstableApi
@Singleton
class SamplerEngine @Inject constructor(
    @param:ApplicationContext private val context: Context,
    private val crossfadeEngine: CrossfadeEngine,
    private val synthesizer: SynthesizedSampleGenerator
) {

    companion object {
        private const val TAG         = "SamplerEngine"
        private const val MAX_STREAMS = 6

        // ── Mid-crossfade trigger fractions ───────────────────────────────────
        // Both fractions are fixed regardless of strategy during the test build.
        private const val MID_FRACTION_1 = 0.30f  // first mid trigger
        private const val MID_FRACTION_2 = 0.55f  // second mid trigger — nadir

        // ── Session-start poll ────────────────────────────────────────────────
        private const val SESSION_HORN_POLL_MS    = 20L
        private const val SESSION_HORN_TIMEOUT_MS = 600L

        // ── Randomised sample pools (all samples rotate across transitions) ───
        //
        // Every sample in the app has a place in one of these four pools so
        // nothing is ever stuck silent. Selection is random-per-crossfade.
        private val START_POOL = listOf(
            SampleId.SIREN,
            SampleId.REWIND_SWEEP,
            // SampleId.DJ_SCRATCH, // <-- Commented out as requested
            SampleId.FOGHORN
        )
        private val MID_1_POOL = listOf(
            SampleId.RISER_SWEEP,
            SampleId.WHITE_NOISE_UP,
            SampleId.WHITE_NOISE_DOWN
        )
        private val MID_2_POOL = listOf(
            SampleId.IMPACT_HIT,
            SampleId.STUTTER_HIT
        )
        private val DROP_POOL = listOf(
            SampleId.AIR_HORN,
            SampleId.CROWD_HEY
        )
    }

    // ── SoundPool state ───────────────────────────────────────────────────────

    private var soundPool: SoundPool? = null

    /** Maps SampleId → SoundPool sound ID returned by SoundPool.load(). */
    private val soundIds     = mutableMapOf<SampleId, Int>()

    /** Tracks which SoundPool sound IDs have fully decoded and are ready to play. */
    private val loadedSounds = mutableSetOf<Int>()

    // ── Settings ──────────────────────────────────────────────────────────────

    /** When false the engine is silent on all auto-triggers; manual pads still work. */
    var isAutoSamplerEnabled: Boolean = true

    /** Volume applied to every sample playback (0.0 – 1.0). */
    var sampleVolume: Float = 0.80f

    // ── Internal ──────────────────────────────────────────────────────────────

    private var samplerScope = CoroutineScope(SupervisorJob() + Dispatchers.Default)
    private var observerJob: Job? = null

    @Volatile private var isInitialized = false
    @Volatile private var isReleased    = false

    /**
     * Tracks which mid-crossfade thresholds have already fired for the current
     * crossfade transition. Cleared each time isCrossfading flips false → true.
     *
     * Accessed only from within the sequential [observerJob] coroutine — no
     * synchronisation needed.
     */
    private val firedMidThresholds = mutableSetOf<Float>()

    /**
     * Samples randomly selected for the CURRENT crossfade — picked once at
     * crossfade-start inside [onCrossfadeStarted] so that [midTriggersFor] and
     * [onDropCompleted] always see a stable, consistent set for that transition.
     * No re-randomisation can happen mid-fade.
     */
    private var selectedMid1Sample: SampleId = SampleId.RISER_SWEEP
    private var selectedMid2Sample: SampleId = SampleId.IMPACT_HIT
    private var selectedDropSample: SampleId = SampleId.AIR_HORN

    val isReady: Boolean get() = isInitialized && !isReleased

    // ═════════════════════════════════════════════════════════════════════════
    // INITIALISATION / RELEASE
    // ═════════════════════════════════════════════════════════════════════════

    fun initialize() {
        if (isInitialized) return

        if (isReleased) {
            samplerScope = CoroutineScope(SupervisorJob() + Dispatchers.Default)
            isReleased   = false
            soundIds.clear()
            loadedSounds.clear()
            firedMidThresholds.clear()
        }

        val audioAttrs = AudioAttributes.Builder()
            .setUsage(AudioAttributes.USAGE_MEDIA)
            .setContentType(AudioAttributes.CONTENT_TYPE_MUSIC)
            .build()

        soundPool = SoundPool.Builder()
            .setMaxStreams(MAX_STREAMS)
            .setAudioAttributes(audioAttrs)
            .build()
            .also { pool ->
                pool.setOnLoadCompleteListener { _, soundId, status ->
                    if (status == 0) {
                        loadedSounds.add(soundId)
                        val name = soundIds.entries.firstOrNull { it.value == soundId }?.key?.name
                        Log.d(TAG, "Loaded: $name (soundId=$soundId)")
                    } else {
                        Log.e(TAG, "Load failed: soundId=$soundId status=$status")
                    }
                }
            }

        loadAllSamples()
        startAutoTriggerObserver()
        isInitialized = true
        Log.d(TAG, "initialize: SamplerEngine ready")
    }

    fun release() {
        if (isReleased) return
        isReleased = true
        observerJob?.cancel()
        samplerScope.cancel()
        soundPool?.release()
        soundPool = null
        soundIds.clear()
        loadedSounds.clear()
        isInitialized = false
        Log.d(TAG, "release: SamplerEngine released")
    }

    // ═════════════════════════════════════════════════════════════════════════
    // SAMPLE LOADING
    // ═════════════════════════════════════════════════════════════════════════

    private fun loadAllSamples() {
        val pool = soundPool ?: return

        // ── Asset-based samples (downloaded CC0 OGG files) ────────────────────
        SampleId.entries.forEach { sampleId ->
            val path = sampleId.assetPath ?: return@forEach
            try {
                val afd     = context.assets.openFd(path)
                val soundId = pool.load(afd, 1)
                afd.close()
                if (soundId > 0) {
                    soundIds[sampleId] = soundId
                    Log.d(TAG, "Queued asset load: ${sampleId.name} → soundId=$soundId")
                } else {
                    Log.e(TAG, "SoundPool.load returned 0 for ${sampleId.name} — check asset path: $path")
                }
            } catch (e: Exception) {
                Log.e(TAG, "Asset load failed for ${sampleId.name}: ${e.message}")
            }
        }

        // ── Synthesized samples ───────────────────────────────────────────────
        samplerScope.launch(Dispatchers.IO) {
            SampleId.entries
                .filter { it.assetPath == null }
                .forEach { sampleId ->
                    try {
                        val file    = synthesizer.getOrGenerate(sampleId)
                        val soundId = pool.load(file.absolutePath, 1)
                        if (soundId > 0) {
                            soundIds[sampleId] = soundId
                            Log.d(TAG, "Queued synthesized load: ${sampleId.name} → soundId=$soundId")
                        } else {
                            Log.e(TAG, "SoundPool.load returned 0 for synthesized ${sampleId.name}")
                        }
                    } catch (e: Exception) {
                        Log.e(TAG, "Synthesized load failed for ${sampleId.name}: ${e.message}")
                    }
                }
        }
    }

    // ═════════════════════════════════════════════════════════════════════════
    // PUBLIC API
    // ═════════════════════════════════════════════════════════════════════════

    /**
     * Plays [sampleId] immediately at [sampleVolume].
     * Safe to call from any thread — SoundPool.play() is thread-safe.
     *
     * Returns the SoundPool stream ID (> 0 on success, 0 on failure).
     */
    fun triggerSample(sampleId: SampleId): Int {
        if (isReleased) return 0
        val pool    = soundPool ?: return 0
        val soundId = soundIds[sampleId] ?: run {
            Log.w(TAG, "triggerSample: ${sampleId.name} not loaded yet — skipping")
            return 0
        }
        if (soundId !in loadedSounds) {
            Log.w(TAG, "triggerSample: ${sampleId.name} still decoding — skipping")
            return 0
        }
        val vol      = sampleVolume.coerceIn(0f, 1f)
        val streamId = pool.play(soundId, vol, vol, 1, 0, 1.0f)
        Log.d(TAG, "triggerSample: ${sampleId.name} streamId=$streamId vol=$vol")
        return streamId
    }

    /**
     * Stops a specific sample stream returned by [triggerSample].
     */
    fun stopSample(streamId: Int) {
        if (isReleased || streamId <= 0) return
        soundPool?.stop(streamId)
        Log.d(TAG, "stopSample: streamId=$streamId")
    }

    /**
     * Immediately pauses ALL currently playing sample streams.
     * Does not affect the CrossfadeEngine or ExoPlayer music.
     */
    fun stopAllSamples() {
        if (isReleased) return
        soundPool?.autoPause()
        Log.d(TAG, "stopAllSamples: autoPause called")
    }

    /**
     * Called once per DJ session when the first track begins playing.
     *
     * Race-condition fix: SoundPool.load() is async. On first launch observeFirstPlay()
     * in AutoMixService fires ~146ms before the OGG decoder finishes (confirmed by logcat),
     * causing triggerSample() to log "still decoding" and produce silence.
     *
     * Fast-path plays immediately if already decoded (all launches after the first).
     * Slow-path polls loadedSounds every SESSION_HORN_POLL_MS until the asset is ready
     * or SESSION_HORN_TIMEOUT_MS elapses. Typical slow-path wait: 20–40 ms.
     */
    fun onSessionStarted() {
        if (isReleased || !isAutoSamplerEnabled) return

        // Fast path: already loaded — play immediately.
        val soundId = soundIds[SampleId.AIR_HORN]
        if (soundId != null && soundId in loadedSounds) {
            triggerSample(SampleId.AIR_HORN)
            Log.d(TAG, "onSessionStarted: AIR_HORN fired immediately — DJ Mix is live")
            return
        }

        // Slow path: decoder hasn't finished yet — wait and retry.
        Log.d(TAG, "onSessionStarted: AIR_HORN not decoded yet — waiting (slow path)")
        samplerScope.launch {
            val startMs = System.currentTimeMillis()
            val sid     = soundIds[SampleId.AIR_HORN] ?: run {
                Log.w(TAG, "onSessionStarted: AIR_HORN has no soundId — asset load may have failed")
                return@launch
            }
            while (!isReleased) {
                if (sid in loadedSounds) {
                    triggerSample(SampleId.AIR_HORN)
                    Log.d(TAG, "onSessionStarted: AIR_HORN fired after " +
                            "${System.currentTimeMillis() - startMs}ms wait — DJ Mix is live")
                    return@launch
                }
                if (System.currentTimeMillis() - startMs > SESSION_HORN_TIMEOUT_MS) {
                    Log.w(TAG, "onSessionStarted: AIR_HORN timed out after " +
                            "${SESSION_HORN_TIMEOUT_MS}ms — skipping")
                    return@launch
                }
                delay(SESSION_HORN_POLL_MS)
            }
        }
    }

    // ═════════════════════════════════════════════════════════════════════════
    // AUTO-TRIGGER OBSERVER
    // ═════════════════════════════════════════════════════════════════════════

    /**
     * Collects [CrossfadeEngine.state] on the Default dispatcher and fires samples
     * at three lifecycle points per crossfade:
     *
     * 1. **START** — isCrossfading flips false → true.
     * A random sample is drawn from [START_POOL] and all mid/drop selections
     * for this transition are locked in via [onCrossfadeStarted].
     *
     * 2. **MID** — crossfadeProgressFraction crosses [MID_FRACTION_1] (30 %) and
     * [MID_FRACTION_2] (55 %). Samples are the pre-selected [selectedMid1Sample]
     * and [selectedMid2Sample] — stable for the entire transition.
     *
     * 3. **DROP** — isCrossfading flips true → false AND currentTrack.id changed.
     * Fires the pre-selected [selectedDropSample].
     *
     * [firedMidThresholds] ensures each threshold fires exactly once per transition
     * even if the state flow emits rapidly around the threshold value.
     */
    private fun startAutoTriggerObserver() {
        observerJob?.cancel()
        observerJob = samplerScope.launch {
            var prev: CrossfadeEngineState? = null

            crossfadeEngine.state.collect { current ->
                val previous = prev
                prev = current

                if (!isAutoSamplerEnabled) return@collect

                // ── 1. Crossfade just STARTED ─────────────────────────────────
                if (previous?.isCrossfading == false && current.isCrossfading) {
                    firedMidThresholds.clear()
                    onCrossfadeStarted(current.currentMixStrategy)
                }

                // ── 2. Mid-crossfade thresholds crossed ───────────────────────
                if (current.isCrossfading) {
                    val midTriggers  = midTriggersFor(current.currentMixStrategy)
                    val prevFraction = previous?.crossfadeProgressFraction ?: 0f
                    val currFraction = current.crossfadeProgressFraction

                    for ((threshold, sample) in midTriggers) {
                        if (threshold !in firedMidThresholds
                            && prevFraction < threshold
                            && currFraction >= threshold
                        ) {
                            firedMidThresholds.add(threshold)
                            triggerSample(sample)
                            Log.d(TAG, "Auto: mid-mix @ ${(threshold * 100).toInt()}% → ${sample.name}")
                        }
                    }
                }

                // ── 3. Crossfade just COMPLETED (track changed) ───────────────
                val trackChanged = previous?.currentTrack?.id != current.currentTrack?.id
                if (previous?.isCrossfading == true && !current.isCrossfading && trackChanged) {
                    onDropCompleted(previous.currentMixStrategy)
                }
            }
        }
    }

    /**
     * Returns the two mid-crossfade (threshold, sample) pairs for this transition.
     *
     * Both samples were locked in by [onCrossfadeStarted] at the moment the
     * crossfade began, so this function is pure read — no randomisation here.
     * The [strategy] parameter is accepted for API compatibility but is not used
     * during the test build (all transitions use the same fixed fractions).
     */
    private fun midTriggersFor(strategy: MixStrategy): List<Pair<Float, SampleId>> = listOf(
        MID_FRACTION_1 to selectedMid1Sample,
        MID_FRACTION_2 to selectedMid2Sample
    )

    // ── Lifecycle callbacks ───────────────────────────────────────────────────

    /**
     * Fires the START sample and locks in mid/drop selections for this crossfade.
     *
     * All four picks happen here — once — so no part of the transition can
     * observe a partially-updated selection set.
     *
     * The [strategy] parameter is accepted for API compatibility but is not used
     * during the test build; the pools cover all strategies equally.
     */
    private fun onCrossfadeStarted(strategy: MixStrategy) {
        // Lock in the full sample set for this transition before firing anything.
        val startSample    = START_POOL.random()
        selectedMid1Sample = MID_1_POOL.random()
        selectedMid2Sample = MID_2_POOL.random()
        selectedDropSample = DROP_POOL.random()

        triggerSample(startSample)
        Log.d(TAG, "Auto: crossfade started → START=$startSample " +
                "mid1=$selectedMid1Sample mid2=$selectedMid2Sample drop=$selectedDropSample")
    }

    /**
     * Fires the DROP sample that was locked in at crossfade-start.
     *
     * The [strategy] parameter is accepted for API compatibility but is not used
     * during the test build.
     */
    private fun onDropCompleted(strategy: MixStrategy) {
        triggerSample(selectedDropSample)
        Log.d(TAG, "Auto: drop completed → $selectedDropSample")
    }
}